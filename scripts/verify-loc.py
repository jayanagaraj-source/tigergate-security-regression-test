# ------------------------------------------------------------------------------------ reference counter
def spec_for(path):
    base = path.name.lower()
    if base in BY_NAME:
        return BY_NAME[base]
    if base.endswith(".gradle.kts") or base in LOCKFILES or base.endswith(".min.js"):
        return None
    return LANGS.get(path.suffix.lower())


def yaml_is_config(text):
    config = False
    for line in text.splitlines()[:2000]:
        if not line or line[0] in " \t#-":
            continue
        key = line.split(":", 1)[0].strip() if ":" in line else None
        if key in ("apiVersion", "kind"):
            return False
        if key in ("services", "spring"):
            config = True
    return config


def is_generated(text):
    return any(GENERATED.match(l.strip()) for l in text.lstrip("﻿").splitlines()[:30])


def python_code_lines(text):
    doc_lines = set()
    tree = ast.parse(text)
    for node in [tree] + [n for n in ast.walk(tree) if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))]:
        body = getattr(node, "body", [])
        if body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant) and isinstance(body[0].value.value, str):
            doc_lines.update(range(body[0].lineno, body[0].end_lineno + 1))
    code = set()
    skip = {tokenize.COMMENT, tokenize.NL, tokenize.NEWLINE, tokenize.INDENT, tokenize.DEDENT, tokenize.ENCODING,
            tokenize.ENDMARKER}
    for tok in tokenize.generate_tokens(io.StringIO(text).readline):
        if tok.type in skip:
            continue
        if tok.type == tokenize.STRING and tok.start[0] in doc_lines:
            continue
        code.update(range(tok.start[0], tok.end[0] + 1))
    return len(code)


def generic_code_lines(text, line_comments, block, quotes):
    code, in_block, in_str = 0, False, None
    for line in text.splitlines():
        has_code, i = False, 0
        while i < len(line):
            if in_block:
                j = line.find(block[1], i)
                if j < 0:
                    break
                in_block, i = False, j + len(block[1])
                continue
            if in_str:
                has_code = True
                if line[i] == "\\":
                    i += 2
                    continue
                if line[i] == in_str:
                    in_str = None
                i += 1
                continue
            if block and line.startswith(block[0], i):
                in_block, i = True, i + len(block[0])
                continue
            if any(line.startswith(c, i) for c in line_comments):
                break
            ch = line[i]
            if ch in quotes and quotes:
                in_str, has_code = ch, True
            elif not ch.isspace():
                has_code = True
            i += 1
        if in_str and in_str != "`":
            in_str = None  # single-line strings never continue
        code += has_code
    return code


def reference_count(path):
    """(counted, language, code) for one file under the documented rules."""
    spec = spec_for(path)
    if spec is None:
        return False, None, 0
    text = path.read_text(encoding="utf-8", errors="replace")
    lang = spec[0]
    if lang == "yaml" and yaml_is_config(text):
        return False, None, 0
    if is_generated(text):
        return False, None, 0
    if lang == "python":
        return True, lang, python_code_lines(text)
    return True, lang, generic_code_lines(text, spec[1], spec[2], spec[3])


def walk(root):
    for p in sorted(root.rglob("*")):
        rel = p.relative_to(root)
        if any(part in SKIP_DIRS for part in rel.parts[:-1]) or not p.is_file():
            continue
        yield rel.as_posix(), p


def build_expected():
    files, errors = [], []
    for rel, p in walk(ROOT):
        if rel.startswith("expected/") or rel.startswith("reports/"):
            continue  # JSON/Markdown outputs: never counted, and they change with every run
        counted, lang, code = reference_count(p)
        entry = {"file": rel, "counted": counted, "language": lang, "code": code, "basis": "reference-counter"}
        if rel in HAND_COUNTS:
            h = HAND_COUNTS[rel]
            entry.update({"basis": "hand-verified", "notes": h[3]})
            if (h[0], h[1], h[2]) != (counted, lang, code):
                errors.append("%s: hand count %s != reference counter %s" % (rel, h[:3], (counted, lang, code)))
        if rel in KNOWN_MODEL_DIVERGENCE:
            entry["tigergate_model_code"] = KNOWN_MODEL_DIVERGENCE[rel]
        entry["sonarcloud"] = "pending"
        if counted or rel.startswith("loc/"):
            files.append(entry)
    for rel in HAND_COUNTS:
        if not (ROOT / rel).is_file():
            errors.append("%s: hand-verified file missing" % rel)
    per_lang = defaultdict(int)
    for f in files:
        if f["counted"]:
            per_lang[f["language"]] += f["code"]
    loc_only = defaultdict(int)
    for f in files:
        if f["counted"] and f["file"].startswith("loc/"):
            loc_only[f["language"]] += f["code"]
    doc = {
        "schema_version": 1,
        "generated_by": "scripts/verify-loc.py --write-manifest",
        "definition": "code lines (ncloc): lines with a non-comment, non-whitespace character; Python docstrings excluded",
        "sonarcloud_status": "pending: no SonarCloud analysis of this exact commit has been compared",
        "totals": {"code": sum(per_lang.values()), "per_language": dict(sorted(per_lang.items()))},
        "loc_fixture_totals": {"code": sum(loc_only.values()), "per_language": dict(sorted(loc_only.items()))},
        "files": files,
    }
    return doc, errors


# ------------------------------------------------------------------------------------------ comparison
def load_actual(path):
    d = json.loads(Path(path).read_text(encoding="utf-8"))
    if isinstance(d, dict) and "metrics_json" in d:
        d = d["metrics_json"] if isinstance(d["metrics_json"], dict) else json.loads(d["metrics_json"])
    total = d.get("code", d.get("lines_of_code"))
    per = d.get("per_language") or d.get("lines_per_language") or {}
    per = {k.lower(): (v.get("code") if isinstance(v, dict) else v) for k, v in per.items()}
    files = {k: (v.get("code") if isinstance(v, dict) else v) for k, v in (d.get("files") or {}).items()}
    return {"code": total, "per_language": per, "files": files}


def load_sonar(paths):
    out = {"code": None, "per_language": {}, "files": {}}
    for p in paths:
        d = json.loads(Path(p).read_text(encoding="utf-8"))
        comp = d.get("component") or {}
        for m in comp.get("measures", []):
            if m.get("metric") == "ncloc":
                out["code"] = int(m["value"])
            if m.get("metric") == "ncloc_language_distribution":
                for part in m["value"].split(";"):
                    k, _, v = part.partition("=")
                    out["per_language"][SONAR_LANG.get(k, k)] = int(v)
        for c in d.get("components", []):
            for m in c.get("measures", []):
                if m.get("metric") == "ncloc" and c.get("path"):
                    out["files"][c["path"]] = int(m["value"])
    return out


def compare(expected, actual, name):
    exp_files = {f["file"]: f for f in expected["files"]}
    res = {"name": name, "expected_total": expected["totals"]["code"], "actual_total": actual["code"]}
    langs = sorted(set(expected["totals"]["per_language"]) | set(actual["per_language"]))
    res["per_language"] = [{"language": l, "expected": expected["totals"]["per_language"].get(l, 0),
                            "actual": actual["per_language"].get(l)} for l in langs]
    if actual["files"]:
        unexpected = sorted(f for f in actual["files"] if not exp_files.get(f, {}).get("counted"))
        missing = sorted(f for f, e in exp_files.items() if e["counted"] and f not in actual["files"])
        mismatched = []
        for f, code in sorted(actual["files"].items()):
            e = exp_files.get(f)
            if e and e["counted"] and e["code"] != code:
                mismatched.append({"file": f, "expected": e["code"], "actual": code,
                                   "known_model_divergence": e.get("tigergate_model_code") == code})
        res.update({"unexpectedly_counted": unexpected, "missing_counted": missing, "per_file_mismatch": mismatched})
    else:
        res["per_file"] = "not available in this export"
    return res


def md_compare(c):
    md = ["### %s" % c["name"], "", "Total code lines: expected **%s**, actual **%s**%s" % (
        c["expected_total"], c["actual_total"],
        "" if c["actual_total"] is None else (" (match)" if c["expected_total"] == c["actual_total"] else " (**differs**)")),
        "", "| Language | Expected | Actual |", "|---|---:|---:|"]
    for r in c["per_language"]:
        flag = "" if r["expected"] == r["actual"] else " ⚠"
        md.append("| %s | %d | %s%s |" % (r["language"], r["expected"], "-" if r["actual"] is None else r["actual"], flag))
    if "per_file_mismatch" in c:
        md += ["", "Unexpectedly counted: %s" % (", ".join("`%s`" % f for f in c["unexpectedly_counted"]) or "none"),
               "", "Missing counted files: %s" % (", ".join("`%s`" % f for f in c["missing_counted"]) or "none"), ""]
        if c["per_file_mismatch"]:
            md += ["| File | Expected | Actual | Note |", "|---|---:|---:|---|"]
            for m in c["per_file_mismatch"]:
                md.append("| `%s` | %d | %d | %s |" % (m["file"], m["expected"], m["actual"],
                                                       "known TigerGate model divergence" if m["known_model_divergence"] else "unexplained"))
        else:
            md.append("Per-file code lines: all match.")
    else:
        md += ["", "Per-file counts: not available in this export."]
    return md


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write-manifest", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--tigergate")
    ap.add_argument("--compare-cli")
    ap.add_argument("--sonar", action="append", default=[])
    ap.add_argument("--label", default="TigerGate")
    ap.add_argument("--json-out")
    ap.add_argument("--md-out")
    a = ap.parse_args(argv)

    doc, errors = build_expected()
    text = json.dumps(doc, indent=2) + "\n"
    if errors:
        print("\n".join("ERROR: " + e for e in errors))
        return 1
    if a.write_manifest:
        MANIFEST.write_text(text, encoding="utf-8")
        print("wrote %s: %d code lines expected (%d in loc/)" % (MANIFEST.name, doc["totals"]["code"], doc["loc_fixture_totals"]["code"]))
        return 0
    if a.check:
        if not MANIFEST.exists() or MANIFEST.read_text(encoding="utf-8") != text:
            print("ERROR: expected/loc.manifest.json is stale (run make manifest)")
            return 1
        print("loc manifest up to date: %d code lines expected" % doc["totals"]["code"])
        return 0

    expected = json.loads(MANIFEST.read_text(encoding="utf-8"))
    included = [f["file"] for f in expected["files"] if f["file"].startswith("loc/") and f["counted"]]
    excluded = [f["file"] for f in expected["files"] if f["file"].startswith("loc/") and not f["counted"]]
    md = ["# LOC comparison", "", "Expected total (whole repository): **%d** code lines; loc/ fixtures: **%d**." % (
        expected["totals"]["code"], expected["loc_fixture_totals"]["code"]), "",
        "Included loc/ files (%d): %s" % (len(included), ", ".join("`%s`" % f for f in included)), "",
        "Excluded loc/ files (%d): %s" % (len(excluded), ", ".join("`%s`" % f for f in excluded)), ""]
    out = {"expected_total": expected["totals"]["code"], "comparisons": []}
    if a.tigergate:
        c = compare(expected, load_actual(a.tigergate), a.label)
        out["comparisons"].append(c)
        md += md_compare(c) + [""]
    else:
        md += ["TigerGate: **unverified** (no export given).", ""]
    if a.compare_cli:
        c = compare(expected, load_actual(a.compare_cli), "CLI counter")
        out["comparisons"].append(c)
        md += md_compare(c) + [""]
        if a.tigergate:
            w, k = load_actual(a.tigergate), load_actual(a.compare_cli)
            same = w["code"] == k["code"] and w["per_language"] == k["per_language"] and w["files"] == k["files"]
            out["worker_cli_identical"] = same
            md += ["Worker vs CLI counter: **%s**" % ("identical" if same else "DIFFERENT"), ""]
    if a.sonar:
        c = compare(expected, load_sonar(a.sonar), "SonarCloud")
        out["comparisons"].append(c)
        md += md_compare(c) + [""]
    else:
        out["sonarcloud"] = "pending"
        md += ["SonarCloud: **pending** (no analysis of this exact commit supplied).", ""]
    if a.json_out:
        Path(a.json_out).write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8")
    if a.md_out:
        Path(a.md_out).write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    sys.exit(main())
