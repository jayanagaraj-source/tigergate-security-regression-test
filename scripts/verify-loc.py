#!/usr/bin/env python3
"""LOC expectations and comparison.

  verify-loc.py --write-manifest            regenerate expected/loc.manifest.json
  verify-loc.py --check                     fail if the manifest is stale or a hand count disagrees
  verify-loc.py --tigergate ACTUAL.json [--compare-cli CLI.json] [--sonar SONAR.json ...]
                [--label L] [--json-out F] [--md-out F]

Expected values are code lines (SonarCloud's ncloc meaning: a line holding at least one character that
is neither whitespace nor part of a comment; Python docstrings are documentation). They come from the
hand-verified table HAND_COUNTS for loc/ and from this script's reference counter for every other file.
Which files count follows TigerGate's documented intent: lockfiles, *.min.js, Gradle Kotlin scripts,
Docker Compose / Spring YAML, README/Makefile and files whose first 30 lines carry a generated-code
marker do not count.

ACTUAL may be the tg-loc output of scripts/local-engine-scan.sh, a LocStats JSON ({code, per_language}),
or a code_quality_metrics.metrics_json export ({lines_of_code, lines_per_language}). SONAR is the JSON of
SonarCloud's api/measures/component (ncloc, ncloc_language_distribution) and/or
api/measures/component_tree (per-file ncloc) for this exact commit; without it SonarCloud is "pending".
"""
import argparse
import ast
import io
import json
import re
import sys
import tokenize
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "expected" / "loc.manifest.json"

